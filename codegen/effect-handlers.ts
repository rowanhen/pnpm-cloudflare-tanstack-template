import { readFile, rm } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import {
	resolveRef,
	pascal,
	conventionName,
	getOperationTagKey,
	type ContextSpec,
	type GeneratorVerbOptions,
	type OpenApiNonBooleanSchemaObject,
	type OpenApiRequestBodyObject,
	type OpenApiResponseObject,
	type OpenApiSchemaObject,
	type OutputClientFunc,
} from 'orval'
const operationFile = (id: string) => conventionName(id, 'kebab-case')

const header = '// Generated by the Orval Effect extension. Do not edit.\n'
// Custom clients also emit TS models; this output only consumes the native Effect schemas.
export async function removeUnusedEffectModels(paths: unknown) {
	if (!Array.isArray(paths)) throw new Error('Orval must supply generated paths to the hook')
	await Promise.all(
		paths
			.filter(
				(file): file is string => typeof file === 'string' && file.endsWith('.schemas.effect.ts'),
			)
			.map((file) => rm(file)),
	)
}
const typeName = (operation: GeneratorVerbOptions) => pascal(operation.typeName)
function resolveSchema(
	schema: OpenApiSchemaObject,
	context: ContextSpec,
): OpenApiNonBooleanSchemaObject {
	if (typeof schema !== 'object') throw new Error('The Effect adapter requires an object schema')
	return '$ref' in schema && typeof schema.$ref === 'string'
		? resolveRef<OpenApiNonBooleanSchemaObject>({ $ref: schema.$ref }, context).schema
		: schema
}
const featureGroups = (operations: Record<string, GeneratorVerbOptions>) => {
	const groups = new Map<string, GeneratorVerbOptions[]>()
	for (const operation of Object.values(operations)) {
		const feature = getOperationTagKey(operation)
		groups.set(feature, [...(groups.get(feature) ?? []), operation])
	}
	return groups
}

// Extend Orval's schema generator with the application's typed HTTP/Effect boundary.
function operationContract(operation: GeneratorVerbOptions, context: ContextSpec) {
	const { operationId: id, originalOperation: spec, pathRoute, verb } = operation
	const name = typeName(operation)
	const security = JSON.stringify(spec.security ?? context.spec.security)
	if (security !== '[]' && security !== JSON.stringify([{ session: [] }]))
		throw new Error(`${id}: this adapter supports public or cookie-session security`)
	const parameters = [
		...(context.spec.paths?.[pathRoute]?.parameters ?? []),
		...(spec.parameters ?? []),
	]
	if (parameters.some((parameter) => '$ref' in parameter || parameter.in !== 'path'))
		throw new Error(`${id}: only path parameters are supported by the Effect adapter`)
	const input = parameters.length ? [`params: ${name}Params`] : []
	if (spec.requestBody) {
		const body = resolveRef<OpenApiRequestBodyObject>(spec.requestBody, context).schema
		const schema = body.content['application/json']?.schema
		if (!body.required || !schema || typeof schema !== 'object')
			throw new Error(`${id}: use a required JSON request body`)
		const resolved = resolveSchema(schema, context)
		// Orval omits minProperties; preserve it at the shared validation boundary.
		input.push(
			`body: ${name}Body${resolved.minProperties === undefined ? '' : `.check(S.isMinProperties(${resolved.minProperties}))`}`,
		)
	}
	const responses = spec.responses ?? {}
	for (const status of [
		'400',
		'401',
		'403',
		'500',
		'503',
		...(spec.requestBody ? ['413', '415'] : []),
	])
		if (!responses[status]) throw new Error(`${id}: declare boundary response ${status}`)
	const errorCodes: string[] = []
	const schemas = Object.entries(responses).map(([status, value]) => {
		if (!/^[245][0-9]{2}$/.test(status)) throw new Error(`${id}: use explicit 2xx/4xx/5xx statuses`)
		if (!value || typeof value !== 'object') throw new Error(`${id}/${status}: invalid response`)
		// Orval has validated this response; its extension-key index signature erases the entry type.
		const response = resolveRef<OpenApiResponseObject>(
			value as OpenApiResponseObject,
			context,
		).schema
		const json = response.content?.['application/json']
		if ((response.content && !json) || (!json && status !== '204'))
			throw new Error(`${id}/${status}: use JSON responses or a bodyless 204`)
		if (Number(status) >= 400) {
			const schema =
				typeof json?.schema === 'object' ? resolveSchema(json.schema, context) : undefined
			const code = schema?.properties?.code
			if (
				!code ||
				typeof code !== 'object' ||
				'$ref' in code ||
				code.enum?.length !== 1 ||
				typeof code.enum[0] !== 'string'
			)
				throw new Error(`${id}/${status}: errors require a singleton string code enum`)
			errorCodes.push(`${status}: ${JSON.stringify(code.enum[0])}`)
		}
		return `${status}: ${json ? `${name}${status}Response` : 'S.Undefined'}`
	})
	return `
export const ${id} = {
 operationId: '${id}', method: '${verb.toUpperCase()}', path: ${JSON.stringify(pathRoute)},
 hasBody: ${Boolean(spec.requestBody)}, input: S.Struct({${input.join(',')}}),
 responses: {${schemas.join(',')}}, errorCodes: {${errorCodes.join(',')}},
} as const
export type ${name}Input = InputOf<typeof ${id}>
export type ${name}Success = SuccessOf<typeof ${id}>
export type ${name}Failure = FailureOf<typeof ${id}>
export type ${name}Handler<R = never> = Handler<typeof ${id}, R>
`
}

export const effectHandlers: OutputClientFunc = (clients) => ({
	...clients.effect,
	header: () => "import type { Handler, InputOf, SuccessOf, FailureOf } from '../operation'\n",
	client: async (operation, options, ...args) => {
		const base = await clients.effect.client(operation, options, ...args)
		return {
			...base,
			implementation: base.implementation + operationContract(operation, options.context),
		}
	},
	extraFiles: async (operations, output, context) => {
		const groups = featureGroups(operations)
		const files = [
			{
				path: resolve(dirname(output.target), 'operations.ts'),
				content: `${header}
${[...groups]
	.map(
		([
			feature,
			items,
		]) => `import { ${items.map((item) => item.operationId).join(', ')} } from './${feature}.effect'
export { ${items
			.flatMap((item) => {
				const name = typeName(item)
				return [
					item.operationId,
					...['Input', 'Success', 'Failure', 'Handler'].map((suffix) => `type ${name}${suffix}`),
				]
			})
			.join(', ')} } from './${feature}.effect'`,
	)
	.join('\n')}
export const operations = [${Object.values(operations)
					.map((operation) => operation.operationId)
					.join(', ')}] as const
`,
			},
			{
				path: resolve(dirname(output.target), 'openapi.json'),
				content: JSON.stringify(context.spec, null, 2) + '\n',
			},
		]
		for (const [feature, items] of groups) {
			files.push({
				path: resolve(context.workspace, `apps/api/src/generated/${feature}.handlers.ts`),
				content: `${header}
import { createFactory } from 'hono/factory'
import * as operations from '@workspace/contracts/operations'
import { ${[...new Set(items.map(({ originalOperation: spec }) => (JSON.stringify(spec.security ?? context.spec.security) === '[]' ? 'publicEffectHandler' : 'effectHandler')))].join(', ')} } from '../contract/handler'
${items.map(({ operationId: id }) => `import { ${id} } from '../features/${feature}/${operationFile(id)}'`).join('\n')}
const factory = createFactory()
${items.map(({ operationId: id, originalOperation: spec }) => `export const ${id}Handlers = factory.createHandlers(${JSON.stringify(spec.security ?? context.spec.security) === '[]' ? 'publicEffectHandler' : 'effectHandler'}(operations.${id}, ${id}))`).join('\n')}
`,
			})
			for (const operation of items) {
				const path = resolve(
					context.workspace,
					`apps/api/src/features/${feature}/${operationFile(operation.operationId)}.ts`,
				)
				try {
					await readFile(path)
					continue
				} catch (error) {
					if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error
				}
				const requestContext =
					JSON.stringify(operation.originalOperation.security ?? context.spec.security) === '[]'
						? 'PublicApiRequest'
						: 'ApiRequest'
				files.push({
					path,
					content: `import type { ${typeName(operation)}Handler } from '@workspace/contracts/operations'
import type { ${requestContext} } from '../../contract/context'
// Replace this placeholder with the business logic; TypeScript rejects unfinished handlers.
export const ${operation.operationId}: ${typeName(operation)}Handler<${requestContext}> = TODO_IMPLEMENT_OPERATION
`,
				})
			}
		}
		return files
	},
})

// Keep native Hono route generation; the Effect extension owns validation and handler wiring.
export const effectHono: OutputClientFunc = (clients) => ({
	...clients.hono,
	extraFiles: async (...args) => {
		if (!clients.hono.extraFiles)
			throw new Error('Orval Hono must provide its extraFiles generator')
		return (await clients.hono.extraFiles(...args)).filter(
			(file) => file.path === args[1].override.hono.compositeRoute,
		)
	},
})
